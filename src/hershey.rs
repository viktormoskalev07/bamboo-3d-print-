fn parse_strokes(s: &str) -> Vec<Stroke> {
    s.split('|')
        .map(|part| {
            part.split_whitespace()
                .filter_map(|p| {
                    let (x, y) = p.split_once(',')?;
                    Some((x.parse::<f64>().ok()?, y.parse::<f64>().ok()?))
                })
                .collect::<Stroke>()
        })
        .filter(|s| !s.is_empty())
        .collect()
}

fn parse_jhf(src: &str) -> HashMap<char, Glyph> {
    let mut map = HashMap::new();
    for (i, line) in src.lines().enumerate() {
        let ch = char::from_u32(32 + i as u32).unwrap_or(' ');
        if line.len() < 10 {
            continue;
        }
        let data = line[8..].as_bytes();
        let v = |b: u8| b as f64 - b'R' as f64;
        let (left, right) = (v(data[0]), v(data[1]));
        let mut strokes: Vec<Stroke> = vec![Vec::new()];
        let mut k = 2;
        while k + 1 < data.len() {
            if data[k] == b' ' && data[k + 1] == b'R' {
                strokes.push(Vec::new());
            } else {
                strokes.last_mut().unwrap().push((v(data[k]), v(data[k + 1])));
            }
            k += 2;
        }
        strokes.retain(|s| !s.is_empty());
        map.insert(ch, Glyph { left, right, strokes });
    }
    map
}

fn small_cap(g: &Glyph) -> Glyph {
    // высота заглавных 21 (−12..9) -> высота строчных 14 (−5..9); ширина ×0.85
    let sy = 14.0 / 21.0;
    let sx = 0.85;
    Glyph {
        left: g.left * sx,
        right: g.right * sx,
        strokes: g.strokes.iter().map(|s| s.iter().map(|&(x, y)| (x * sx, 9.0 - (9.0 - y) * sy)).collect()).collect(),
    }
}

impl Hershey {
    fn build() -> Hershey {
        let mut glyphs = parse_jhf(FUTURAL);
        for &(c, l, r, s) in CYR_UPPER.iter().chain(CYR_LOWER.iter()) {
            glyphs.insert(c, Glyph { left: l as f64, right: r as f64, strokes: parse_strokes(s) });
        }
        for &(c, src) in ALIASES {
            if let Some(g) = glyphs.get(&src).cloned() {
                glyphs.insert(c, g);
            }
        }
        for &(c, src) in SMALL_CAPS {
            if let Some(g) = glyphs.get(&src).cloned() {
                glyphs.insert(c, small_cap(&g));
            }
        }
        Hershey { glyphs }
    }

    pub fn get() -> &'static Hershey {
        static H: OnceLock<Hershey> = OnceLock::new();
        H.get_or_init(Hershey::build)
    }

    pub fn glyph(&self, c: char) -> Option<&Glyph> {
        self.glyphs.get(&c).or_else(|| self.glyphs.get(&'?'))
    }

    #[cfg(test)]
    pub fn has(&self, c: char) -> bool {
        self.glyphs.contains_key(&c)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn covers_russian_alphabet() {
        let h = Hershey::get();
        for c in "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯабвгдеёжзийклмнопрстуфхцчшщъыьэюя0123456789ABCabc.,!?".chars() {
            assert!(h.has(c), "нет глифа для {c}");
            assert!(!h.glyph(c).unwrap().strokes.is_empty(), "пустой глиф {c}");
        }
    }
}
