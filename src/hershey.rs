//! Встроенный однолинейный шрифт для пера: каждая буква рисуется ОДНОЙ линией.
//! Латиница, цифры, знаки — Hershey Futura Light (общественное достояние).
//! Кириллица — собрана в той же сетке: совпадающие с латиницей буквы берутся как есть,
//! остальные нарисованы вручную; строчные «малые капители» получаются масштабированием заглавных.
//!
//! Координаты Hershey: Y вниз, верх заглавных −12, базовая линия 9, верх строчных −5, низ выносных 16.

use std::collections::HashMap;
use std::sync::OnceLock;

pub type Stroke = Vec<(f64, f64)>;

#[derive(Clone)]
pub struct Glyph {
    pub left: f64,
    pub right: f64,
    pub strokes: Vec<Stroke>,
}

pub struct Hershey {
    glyphs: HashMap<char, Glyph>,
}

